#!/usr/bin/env node
// Downloads every image in images.manifest.json from Wikimedia Commons at
// the optimised web width and regenerates public/images/ATTRIBUTION.md.
// Every image in the manifest is used under a Commons licence; the
// attribution table is generated from the same source of truth.
import { existsSync } from 'node:fs';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = resolve(rootDir, 'images.manifest.json');
const imagesDir = resolve(rootDir, 'public/images');
const attributionPath = resolve(imagesDir, 'ATTRIBUTION.md');
const userAgent = 'tim-curry-in-nz-site/0.1 (https://tim-curry-in-nz.vercel.app)';
const force = process.argv.includes('--force');

const { images } = JSON.parse(await readFile(manifestPath, 'utf8'));

await mkdir(imagesDir, { recursive: true });

const download = async (url, destination) => {
  const response = await fetch(url, { headers: { 'User-Agent': userAgent } });
  if (!response.ok) {
    throw new Error(`GET ${url} failed with ${response.status}`);
  }
  await writeFile(destination, Buffer.from(await response.arrayBuffer()));
};

const thumbUrl = async (commonsFile, width) => {
  const api = new URL('https://commons.wikimedia.org/w/api.php');
  api.searchParams.set('action', 'query');
  api.searchParams.set('titles', `File:${commonsFile}`);
  api.searchParams.set('prop', 'imageinfo');
  api.searchParams.set('iiprop', 'url');
  api.searchParams.set('iiurlwidth', String(width));
  api.searchParams.set('format', 'json');
  const response = await fetch(api, { headers: { 'User-Agent': userAgent } });
  if (!response.ok) {
    throw new Error(`Commons API failed for ${commonsFile}: ${response.status}`);
  }
  const data = await response.json();
  const page = Object.values(data.query.pages)[0];
  const info = page?.imageinfo?.[0];
  const url = info?.thumburl ?? info?.url;
  if (!url) {
    throw new Error(`No image URL found for ${commonsFile}`);
  }
  return url;
};

const downloadedRows = [];
for (const image of images) {
  const destination = resolve(imagesDir, image.localFile);
  if (existsSync(destination) && !force) {
    console.log(`skip ${image.localFile} (exists; use --force to refresh)`);
  } else {
    const url = await thumbUrl(image.commonsFile, image.width);
    await download(url, destination);
    console.log(`downloaded ${image.localFile} at ${image.width}px`);
  }
  downloadedRows.push(
    `| \`${image.localFile}\` | ${image.credit} | ${image.license} | ${image.sourceUrl} |`
  );
}

const attribution = `# Image attribution

Every photograph in this repository is used under its Wikimedia Commons
licence. Credit and licence appear inline next to each image on the site.
This table is generated by \`npm run images:sync\` from
\`images.manifest.json\`.

| File | Credit | Licence | Source |
| --- | --- | --- | --- |
${downloadedRows.join('\n')}
`;

await writeFile(attributionPath, attribution);
console.log(`wrote ${attributionPath}`);
